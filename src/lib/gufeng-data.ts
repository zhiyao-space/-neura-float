export function ganzhiYear(date: Date): { ganzhi: string; zodiac: string } {
    // 以立春近似的农历年计（简化按公历年，倒退到 2 月 4 日前算前一年）
    const y = date.getMonth() === 0 && date.getDate() < 4 ? date.getFullYear() - 1 : date.getFullYear();
    const idx = (y - 4) % 60;
    return {
        ganzhi: `${STEMS[idx % 10]}${BRANCHES[idx % 12]}`,
        zodiac: ZODIAC[idx % 12],
    };
}
