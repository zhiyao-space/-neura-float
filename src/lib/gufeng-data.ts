export function buildGufengPersona(name: string, desc: string, tags: string[]): string {
    const parts = [`角色名「${name}」`];
    if (desc) parts.push(`其设定：${desc.slice(0, 120)}`);
    if (tags.length) parts.push(`标签：${tags.join("、")}`);
    return parts.join("；");
}

